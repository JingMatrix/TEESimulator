let currentLang = localStorage.getItem("teesim_lang") || "en";

export function setLanguage(lang) {
  if (dictionaries[lang]) {
    currentLang = lang;
    localStorage.setItem("teesim_lang", lang);
    window.location.reload();
  }
}

export function getLanguage() {
  return currentLang;
}

export function t(key, defaultVal) {
  const dict = dictionaries[currentLang] || dictionaries["en"];
  if (dict[key] !== undefined) return dict[key];
  // Fallback to English
  if (dictionaries["en"][key] !== undefined) return dictionaries["en"][key];
  return defaultVal !== undefined ? defaultVal : key;
}

// Translate all elements with data-i18n attribute in the current DOM
export function translateDOM(root = document) {
  const elements = root.querySelectorAll("[data-i18n]");
  for (const el of elements) {
    const key = el.getAttribute("data-i18n");
    if (key) {
      el.textContent = t(key);
    }
  }
}
